// CurrencySum sums the documents of one currency matching a list filter.
type CurrencySum struct {
	Currency     string `json:"currency" example:"CZK"`
	Count        int64  `json:"count"`
	SumTotal     int64  `json:"sum_total" doc:"Σ total (minor units)"`
	SumRemaining int64  `json:"sum_remaining" doc:"Σ (total − paid) of unpaid (open/sent) documents; overpayments of paid documents are not netted"`
}

// DocumentList is a list page plus sums over the whole filter (all pages).
type DocumentList[T any] struct {
	ListResponse[T]
	Sums []CurrencySum `json:"sums" nullable:"false" doc:"Per currency, over every page of the filter"`
}

// currencySums sums total and remaining per currency over q (filtered, not ordered).
func currencySums(q *gorm.DB) ([]CurrencySum, error) {
	out := []CurrencySum{}
	err := q.Session(&gorm.Session{}).
		Select(`currency, COUNT(*) AS count, COALESCE(SUM(total), 0) AS sum_total,
			COALESCE(SUM(CASE WHEN status IN ? THEN total - paid_amount ELSE 0 END), 0) AS sum_remaining`,
			[]string{model.StatusOpen, model.StatusSent}).
		Group("currency").Order("currency").Scan(&out).Error
	if err != nil {
		return nil, dbErr(err, "sums")
	}
	return out, nil
}
