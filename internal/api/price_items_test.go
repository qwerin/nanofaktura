// ---- helpers ----

func piURL(c *client, id uint, suffix string) string {
	return fmt.Sprintf("%s/%d%s", c.acct("/price-items"), id, suffix)
}

func newPriceItem(c *client, body api.PriceItemCreate) api.PriceItem {
	c.ts.t.Helper()
	return doJSON[api.PriceItem](c, http.StatusCreated, "POST", c.acct("/price-items"), body)
}

func getPI(c *client, id uint) api.PriceItem {
	c.ts.t.Helper()
	return doJSON[api.PriceItem](c, http.StatusOK, "GET", piURL(c, id, ""), nil)
}

func listPI(c *client, query string) api.ListResponse[api.PriceItem] {
	c.ts.t.Helper()
	return doJSON[api.ListResponse[api.PriceItem]](c, http.StatusOK, "GET", c.acct("/price-items")+query, nil)
}

func piNames(l api.ListResponse[api.PriceItem]) string {
	out := []string{}
	for _, i := range l.Items {
		out = append(out, i.Name)
	}
	return fmt.Sprint(out)
}

func stockMoves(c *client, itemID uint) []api.StockMove {
	c.ts.t.Helper()
	return doJSON[api.ListResponse[api.StockMove]](c, http.StatusOK, "GET", piURL(c, itemID, "/stock-moves?per_page=200"), nil).Items
}

// assertStock checks the item's stock_quantity and that it equals Σ moves.
func assertStock(t *testing.T, c *client, itemID uint, want string) {
	t.Helper()
	item := getPI(c, itemID)
	if item.StockQuantity != want {
		t.Fatalf("stock %s, want %s", item.StockQuantity, want)
	}
	var sum float64
	for _, m := range stockMoves(c, itemID) {
		var q float64
		fmt.Sscan(m.Quantity, &q)
		if m.Direction == "out" {
			q = -q
		}
		sum += q
	}
	if got := fmt.Sprint(sum); got != want {
		t.Fatalf("Σ moves %s ≠ stock %s", got, want)
	}
}

// invoiceMove returns the only stock move of item generated by invoice invID.
func invoiceMove(t *testing.T, c *client, itemID, invID uint) api.StockMove {
	t.Helper()
	var found []api.StockMove
	for _, m := range stockMoves(c, itemID) {
		if m.InvoiceID != nil && *m.InvoiceID == invID {
			found = append(found, m)
		}
	}
	if len(found) != 1 {
		t.Fatalf("moves of invoice %d: %+v", invID, found)
	}
	return found[0]
}

