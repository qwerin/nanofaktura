func TestInvoiceStock(t *testing.T) {
	ts := newTestServer(t)
	a := ts.signup("a@example.cz", "Firma A")
	subj := newSubject(a, api.SubjectCreate{Name: "ACME"})
	tracked := newPriceItem(a, api.PriceItemCreate{Name: "Myš", TrackStock: true, StockQuantity: "10"})
	plain := newPriceItem(a, api.PriceItemCreate{Name: "Montáž"})
	itemLine := func(id uint, qty string) api.InvoiceLineInput {
		l := line("X", qty, 100, nil)
		l.PriceItemID = &id
		return l
	}

	// create: tracked line moves out, untracked and unlinked lines do not
	inv := createInv(a, api.InvoiceCreate{SubjectID: new(subj.ID), IssuedOn: "2026-03-10", Lines: []api.InvoiceLineInput{
		itemLine(tracked.ID, "2"), itemLine(plain.ID, "1"), line("Doprava", "1", 100, nil),
	}})
	if inv.Lines[0].PriceItemID == nil || *inv.Lines[0].PriceItemID != tracked.ID {
		t.Fatalf("price_item_id: %+v", inv.Lines)
	}
	assertStock(t, a, tracked.ID, "8")
	mv := invoiceMove(t, a, tracked.ID, inv.ID)
	if mv.Direction != "out" || mv.Quantity != "2" || mv.MovedOn != "2026-03-10" || mv.InvoiceID == nil || *mv.InvoiceID != inv.ID {
		t.Fatalf("invoice move: %+v", mv)
	}
	if len(stockMoves(a, plain.ID)) != 0 {
		t.Fatal("untracked item got a move")
	}
	// generated moves cannot be deleted manually
	res, body := a.do("DELETE", piURL(a, tracked.ID, fmt.Sprintf("/stock-moves/%d", mv.ID)), nil)
	assertError(t, res, body, http.StatusConflict, "generated from a document")

	// proforma does not move stock
	pro := createInv(a, api.InvoiceCreate{DocumentType: "proforma", SubjectID: new(subj.ID), Lines: []api.InvoiceLineInput{itemLine(tracked.ID, "5")}})
	assertStock(t, a, tracked.ID, "8")

	// PATCH rewrites the moves: quantity change, line removal, re-adding
	a.mustDo(http.StatusOK, "PATCH", invURL(a, inv.ID, ""), api.InvoicePatch{Lines: []api.InvoiceLineInput{itemLine(tracked.ID, "3.5")}})
	assertStock(t, a, tracked.ID, "6.5")
	a.mustDo(http.StatusOK, "PATCH", invURL(a, inv.ID, ""), api.InvoicePatch{Lines: []api.InvoiceLineInput{line("Jiné", "1", 1, nil)}})
	assertStock(t, a, tracked.ID, "10")
	a.mustDo(http.StatusOK, "PATCH", invURL(a, inv.ID, ""), api.InvoicePatch{Lines: []api.InvoiceLineInput{itemLine(tracked.ID, "2")}})
	assertStock(t, a, tracked.ID, "8")
	// a PATCH without lines keeps the moves (moved_on follows issued_on)
	a.mustDo(http.StatusOK, "PATCH", invURL(a, inv.ID, ""), map[string]any{"issued_on": "2026-03-12"})
	assertStock(t, a, tracked.ID, "8")
	if mv := invoiceMove(t, a, tracked.ID, inv.ID); mv.MovedOn != "2026-03-12" {
		t.Fatalf("moved_on: %+v", mv)
	}
	// foreign/missing price item → 422 on PATCH too
	res, body = a.do("PATCH", invURL(a, inv.ID, ""), api.InvoicePatch{Lines: []api.InvoiceLineInput{itemLine(9999, "1")}})
	assertError(t, res, body, http.StatusUnprocessableEntity, "lines[0].price_item_id")
	assertStock(t, a, tracked.ID, "8")

	// cancel returns the goods, undo_cancel takes them again
	action(a, inv.ID, "cancel")
	assertStock(t, a, tracked.ID, "10")
	action(a, inv.ID, "undo_cancel")
	assertStock(t, a, tracked.ID, "8")
	action(a, inv.ID, "mark_as_sent") // other actions do not touch stock
	assertStock(t, a, tracked.ID, "8")

	// correction (negative quantities) returns the goods
	corr := doJSON[api.Invoice](a, http.StatusCreated, "POST", invURL(a, inv.ID, "/correction"), map[string]any{"correction_reason": "Vrácení zboží"})
	if corr.Lines[0].Quantity != "-2" || corr.Lines[0].PriceItemID == nil {
		t.Fatalf("correction lines: %+v", corr.Lines)
	}
	assertStock(t, a, tracked.ID, "10")
	if mv := invoiceMove(t, a, tracked.ID, corr.ID); mv.Direction != "in" || mv.Quantity != "2" {
		t.Fatalf("correction move: %+v", mv)
	}
	a.mustDo(http.StatusNoContent, "DELETE", invURL(a, corr.ID, ""), nil)
	assertStock(t, a, tracked.ID, "8")

	// deleting the invoice returns its goods
	a.mustDo(http.StatusNoContent, "DELETE", invURL(a, inv.ID, ""), nil)
	assertStock(t, a, tracked.ID, "10")

	// deleting a cancelled invoice does not return the goods twice
	inv2 := createInv(a, api.InvoiceCreate{SubjectID: new(subj.ID), Lines: []api.InvoiceLineInput{itemLine(tracked.ID, "1")}})
	assertStock(t, a, tracked.ID, "9")
	action(a, inv2.ID, "cancel")
	a.mustDo(http.StatusNoContent, "DELETE", invURL(a, inv2.ID, ""), nil)
	assertStock(t, a, tracked.ID, "10")

	// the final invoice created from a paid proforma moves stock out
	r := pay(a, pro.ID, api.PaymentCreate{CreateFinalInvoice: true})
	if r.FinalInvoiceID == nil {
		t.Fatal("no final invoice")
	}
	assertStock(t, a, tracked.ID, "5")

	// duplicate moves stock too
	dup := doJSON[api.Invoice](a, http.StatusCreated, "POST", invURL(a, *r.FinalInvoiceID, "/duplicate"), nil)
	assertStock(t, a, tracked.ID, "0")

	// deleting the price item unlinks the lines and drops its moves
	a.mustDo(http.StatusNoContent, "DELETE", piURL(a, tracked.ID, ""), nil)
	if g := getInv(a, dup.ID); g.Lines[0].PriceItemID != nil {
		t.Fatalf("line still linked: %+v", g.Lines[0])
	}
	a.mustDo(http.StatusNoContent, "DELETE", invURL(a, dup.ID, ""), nil) // no moves left, nothing to revert
}

func TestExpenseStock(t *testing.T) {
	ts := newTestServer(t)
	a := ts.signup("a@example.cz", "Firma A")
	item := newPriceItem(a, api.PriceItemCreate{Name: "Myš", TrackStock: true})
	l := line("Myš", "5", 100, nil)
	l.PriceItemID = &item.ID
	supplier := "Dodavatel"

	exp := createExp(a, api.ExpenseCreate{ExpenseSupplierFields: api.ExpenseSupplierFields{SupplierName: &supplier}, IssuedOn: "2026-03-01", Lines: []api.InvoiceLineInput{l}})
	assertStock(t, a, item.ID, "5")
	mv := stockMoves(a, item.ID)[0]
	if mv.Direction != "in" || mv.ExpenseID == nil || *mv.ExpenseID != exp.ID || mv.MovedOn != "2026-03-01" {
		t.Fatalf("expense move: %+v", mv)
	}
	l.Quantity = "7"
	a.mustDo(http.StatusOK, "PATCH", expURL(a, exp.ID, ""), api.ExpensePatch{Lines: []api.InvoiceLineInput{l}})
	assertStock(t, a, item.ID, "7")
	res, body := a.do("DELETE", piURL(a, item.ID, fmt.Sprintf("/stock-moves/%d", stockMoves(a, item.ID)[0].ID)), nil)
	assertError(t, res, body, http.StatusConflict, "generated from a document")
	a.mustDo(http.StatusNoContent, "DELETE", expURL(a, exp.ID, ""), nil)
	assertStock(t, a, item.ID, "0")
}
